"""Check source-plan integrity and export a portable view of the native roadmap."""

import argparse
import hashlib
import json
from pathlib import Path
import re
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parents[1]
SOURCE_SHA256 = "bfa563dfdab513089d9006581eae0011a78a1d67e46e885cb4db0e84adbaf26c"


def check_roadmap(state: dict) -> None:
    tasks = state["tasks"]
    by_id = {task["id"]: task for task in tasks}
    if len(by_id) != len(tasks):
        raise ValueError("duplicate roadmap task IDs")
    visited, visiting = set(), set()

    def visit(task_id: str) -> None:
        if task_id not in by_id:
            raise ValueError(f"missing dependency: {task_id}")
        if task_id in visiting:
            raise ValueError(f"roadmap cycle at {task_id}")
        if task_id in visited:
            return
        visiting.add(task_id)
        task = by_id[task_id]
        if not task.get("acceptance"):
            raise ValueError(f"missing acceptance: {task_id}")
        for dependency in task.get("dependsOn", []):
            visit(dependency)
            if task["status"] == "done" and by_id[dependency]["status"] != "done":
                raise ValueError(f"completed task has incomplete dependency: {task_id}")
        visiting.remove(task_id)
        visited.add(task_id)

    for task_id in by_id:
        visit(task_id)


def portable_roadmap(state: dict) -> str:
    lines = ["# Roadmap portable", "",
             "<!-- Generated by scripts/check_project.py; edit progress only through native project_roadmap. -->", "",
             "Bản đọc độc lập OMP, sinh từ `.omp/roadmap/roadmap.json`; không chứa workspace binding hoặc receipts.", "",
             f"Revision: {state['revision']}. Một task done không chứng nhận các gate sau đã đạt.", ""]
    phase = None
    for task in state["tasks"]:
        if task["phase"] != phase:
            phase = task["phase"]
            lines.extend([f"## {phase}", ""])
        lines.extend([f"### `{task['id']}` — {task['title']}", "",
                      f"Status: **{task['status']}**. Dependencies: "
                      + (", ".join(f"`{dep}`" for dep in task.get("dependsOn", [])) or "none") + ".", ""])
        lines.extend(f"- {criterion}" for criterion in task["acceptance"])
        # The native API owns blocker schema; omit raw execution/session metadata.
        if task.get("blocker"):
            lines.extend(["", f"Blocker: {task['blocker']}"])
        lines.append("")
    return "\n".join(lines)


def check() -> tuple[dict, str]:
    pdf = ROOT / "docs/source/drone-obstacle-avoidance-plan.pdf"
    if hashlib.sha256(pdf.read_bytes()).hexdigest() != SOURCE_SHA256:
        raise ValueError("original plan PDF checksum mismatch")
    state = json.loads((ROOT / ".omp/roadmap/roadmap.json").read_text(encoding="utf-8"))
    check_roadmap(state)
    documents = [ROOT / "README.md", ROOT / ".omp/AGENTS.md", *sorted((ROOT / "docs").glob("*.md"))]
    scenario_text = (ROOT / "docs/SCENARIOS.md").read_text(encoding="utf-8")
    ids = re.findall(r"^\| ([A-F]\d{2}) \|", scenario_text, re.M)
    expected = {f"{letter}{n:02}" for letter, count in
                [("A", 10), ("B", 7), ("C", 8), ("D", 5), ("E", 25), ("F", 10)]
                for n in range(1, count+1)}
    if len(ids) != len(expected) or set(ids) != expected:
        raise ValueError("scenario table has missing/duplicate IDs")
    for document in documents:
        text = document.read_text(encoding="utf-8")
        for reference in re.findall(r"\b[A-F]\d{2}\b", text):
            if reference not in expected:
                raise ValueError(f"undefined scenario {reference} in {document.name}")
        for target in re.findall(r"\[[^\]]*\]\(([^)]+)\)", text):
            if re.match(r"https?://|mailto:|#", target):
                continue
            local = (document.parent / unquote(target.split("#")[0])).resolve()
            if not local.is_relative_to(ROOT) or not local.exists():
                raise ValueError(f"invalid local link in {document.name}: {target}")
    for task in state["tasks"]:
        for reference in re.findall(r"\b[A-F]\d{2}\b", " ".join(task["acceptance"])):
            if reference not in expected:
                raise ValueError(f"undefined scenario {reference} in {task['id']}")
    summary = f"Integrity OK: PDF checksum, {len(state['tasks'])} acyclic tasks, 65 scenario IDs and local links"
    return state, summary


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--export-roadmap", action="store_true",
                        help="Regenerate docs/ROADMAP.md from canonical native state")
    args = parser.parse_args()
    try:
        state, summary = check()
        portable = ROOT / "docs/ROADMAP.md"
        content = portable_roadmap(state)
        if args.export_roadmap:
            portable.write_text(content, encoding="utf-8")
        elif not portable.is_file() or portable.read_text(encoding="utf-8") != content:
            raise ValueError("portable roadmap stale; run python scripts/check_project.py --export-roadmap")
    except (OSError, ValueError, KeyError, TypeError) as error:
        parser.exit(1, f"Integrity check failed: {error}\n")
    print(summary)


if __name__ == "__main__":
    main()
