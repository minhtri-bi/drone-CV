"""Check source-plan integrity and export a portable view of the native roadmap."""

import argparse
import hashlib
import json
from pathlib import Path
import re
from urllib.parse import unquote
import tarfile
from pathlib import PurePosixPath

ROOT = Path(__file__).resolve().parents[1]
SOURCE_SHA256 = "bfa563dfdab513089d9006581eae0011a78a1d67e46e885cb4db0e84adbaf26c"


def check_roadmap(state: dict) -> None:
    tasks = state["tasks"]
    by_id = {task["id"]: task for task in tasks}
    if len(by_id) != len(tasks):
        raise ValueError("duplicate roadmap task IDs")
    visited, visiting = set(), set()

    def visit(task_id: str) -> None:
        if task_id not in by_id:
            raise ValueError(f"missing dependency: {task_id}")
        if task_id in visiting:
            raise ValueError(f"roadmap cycle at {task_id}")
        if task_id in visited:
            return
        visiting.add(task_id)
        task = by_id[task_id]
        if not task.get("acceptance"):
            raise ValueError(f"missing acceptance: {task_id}")
        for dependency in task.get("dependsOn", []):
            visit(dependency)
            if task["status"] == "done" and by_id[dependency]["status"] != "done":
                raise ValueError(f"completed task has incomplete dependency: {task_id}")
        visiting.remove(task_id)
        visited.add(task_id)

    for task_id in by_id:
        visit(task_id)
    # Supplemental approved gate: the native API cannot edit existing DAG edges.
    # Missing preparation state is not permission to complete a G2 gate.
    semantics = by_id.get("prep-evidence-semantics")
    for task_id, task in by_id.items():
        if (task_id.startswith("g2-") and task["status"] == "done"
                and (semantics is None or semantics["status"] != "done")):
            raise ValueError(f"G2 evidence-semantics gate unmet: {task_id}")
    supplemental = {
        "prep-evidence-review": tuple(key for key in by_id if key.startswith("g2-")),
        "prep-flight-oracle": ("g1-flight",),
        "prep-depth-path-audit": ("g1-calibration",),
    }
    for preparation, gates in supplemental.items():
        for gate in gates:
            task = by_id.get(gate)
            # Flight-oracle preparation is a preflight, not merely a completion gate.
            guarded = ("in_progress", "done") if gate == "g1-flight" else ("done",)
            if (task and task["status"] in guarded
                    and by_id.get(preparation, {}).get("status") != "done"):
                raise ValueError(f"supplemental preparation gate unmet: {preparation} for {gate}")


def english_task_labels(task: dict, labels: dict) -> dict:
    entry = labels[task["id"]]
    if set(entry) != {"source_sha256", "phase", "title", "acceptance"}:
        raise ValueError(f"English labels must contain display metadata only: {task['id']}")
    source = {key: task[key] for key in ("title", "phase", "acceptance")}
    encoded = json.dumps(source, ensure_ascii=False, sort_keys=True,
                         separators=(",", ":")).encode("utf-8")
    if entry["source_sha256"] != hashlib.sha256(encoded).hexdigest():
        raise ValueError(f"English labels stale for {task['id']}; translate current native metadata")
    if (not isinstance(entry["acceptance"], list)
            or len(entry["acceptance"]) != len(task["acceptance"])
            or any(not isinstance(value, str) or not value.strip()
                   for value in [entry["phase"], entry["title"], *entry["acceptance"]])):
        raise ValueError(f"incomplete English labels for {task['id']}")
    return entry


def portable_roadmap(state: dict, labels: dict) -> str:
    if set(labels) != {task["id"] for task in state["tasks"]}:
        raise ValueError("English labels must cover exactly the native task IDs")
    lines = ["# Portable roadmap", "",
             "<!-- Generated by scripts/check_project.py; edit progress only through native project_roadmap. -->", "",
             "Progress comes from `.omp/roadmap/roadmap.json`; English display text comes from `docs/roadmap.en.json`. Workspace binding and receipts are excluded.", "",
             f"Revision: {state['revision']}. A completed task does not certify that later gates have passed.", ""]
    lines.extend([
        "Supplemental checker gates (not native DAG edges): `prep-evidence-review` "
        "before G2 completion; `prep-flight-oracle` before G1 flight starts; "
        "`prep-depth-path-audit` before G1 calibration completes. "
        "Geometry contradictions block affected-profile use. See [repair plan](SIM_REPAIR_PLAN.md).", ""])
    phase = None
    for task in state["tasks"]:
        entry = english_task_labels(task, labels)
        if entry["phase"] != phase:
            phase = entry["phase"]
            lines.extend([f"## {phase}", ""])
        lines.extend([f"### `{task['id']}` — {entry['title']}", "",
                      f"Status: **{task['status']}**. Dependencies: "
                      + (", ".join(f"`{dep}`" for dep in task.get("dependsOn", [])) or "none") + ".", ""])
        lines.extend(f"- {criterion}" for criterion in entry["acceptance"])
        # The native API owns blocker schema; omit raw execution/session metadata.
        if task.get("blocker"):
            lines.extend(["", f"Blocker (verbatim native diagnostic): {task['blocker']}"])
        lines.append("")
    return "\n".join(lines)


def check_evidence_archive(path: Path) -> None:
    with tarfile.open(path, "r:gz") as archive:
        members = archive.getmembers()
        names = [member.name for member in members]
        if (len(names) != len(set(names)) or sum(member.size for member in members) > 2*1024**3
                or any(PurePosixPath(name).is_absolute() or ".." in PurePosixPath(name).parts
                       or "\\" in name for name in names)
                or any(not (member.isfile() or member.isdir()) for member in members)):
            raise ValueError(f"unsafe evidence archive: {path.name}")
        manifests = [member for member in members if member.isfile()
                     and PurePosixPath(member.name).name == "manifest.json"]
        if len(manifests) != 1:
            raise ValueError(f"ambiguous evidence manifest: {path.name}")
        manifest_member = manifests[0]
        manifest = json.load(archive.extractfile(manifest_member))
        root = PurePosixPath(manifest_member.name).parent
        declared = {}
        for name, identity in manifest["bag_files"].items():
            relative = PurePosixPath(name)
            if relative.is_absolute() or ".." in relative.parts or "\\" in name:
                raise ValueError(f"unsafe bag member: {name}")
            declared[str(root / relative)] = identity
        actual_bag = {member.name for member in members if member.isfile()
                      and PurePosixPath(member.name).parent == root / "bag"}
        if actual_bag != set(declared):
            raise ValueError(f"bag member coverage mismatch: {path.name}")
        for name, identity in declared.items():
            member = archive.getmember(name)
            if (member.size != identity["bytes"]
                    or hashlib.file_digest(archive.extractfile(member), "sha256").hexdigest() != identity["sha256"]):
                raise ValueError(f"archived bag identity mismatch: {path.name}:{name}")
        identities = {"fixture.json": manifest["fixture_sha256"]}
        if manifest.get("recording_schema") in (2, 3, 4):
            identities.update({"recording_policy.json": manifest["policy_sha256"],
                               "receive_progress.jsonl": manifest["receive_progress_sha256"]})
        if manifest.get("recording_schema") == 4:
            identities["oracle_profile.json"] = manifest["oracle_profile_sha256"]
        for name, expected in identities.items():
            if hashlib.file_digest(archive.extractfile(str(root / name)), "sha256").hexdigest() != expected:
                raise ValueError(f"archived provenance mismatch: {path.name}:{name}")


def check_evidence_bundle(directory: Path) -> int:
    listed = {}
    for line in (directory / "SHA256SUMS").read_text(encoding="utf-8").splitlines():
        match = re.fullmatch(r"([0-9a-f]{64})  ([A-Za-z0-9][A-Za-z0-9_.-]*)", line)
        if not match or match[2] in listed or match[2] in (".", "..", "SHA256SUMS"):
            raise ValueError(f"invalid evidence checksum entry: {directory.name}")
        listed[match[2]] = match[1]
    actual = {path.name for path in directory.iterdir() if path.is_file() and path.name != "SHA256SUMS"}
    if not listed or actual != set(listed):
        raise ValueError(f"evidence checksum coverage mismatch: {directory.name}")
    for name, expected in listed.items():
        path = directory / name
        if path.is_symlink():
            raise ValueError(f"evidence symlink refused: {directory.name}/{name}")
        with path.open("rb") as stream:
            actual_hash = hashlib.file_digest(stream, "sha256").hexdigest()
        if actual_hash != expected:
            raise ValueError(f"evidence checksum mismatch: {directory.name}/{name}")
        if name.endswith(".tar.gz"):
            check_evidence_archive(path)
    return len(listed)


def check_evidence_root(root: Path) -> int:
    count = 0
    for directory in root.iterdir():
        if directory.is_symlink() or not directory.is_dir():
            raise ValueError(f"unexpected evidence root entry: {directory.name}")
        if not (directory / "SHA256SUMS").is_file():
            raise ValueError(f"missing evidence checksum inventory: {directory.name}")
        count += check_evidence_bundle(directory)
    if not count:
        raise ValueError("empty evidence root")
    return count


def check() -> tuple[dict, str]:
    pdf = ROOT / "docs/source/drone-obstacle-avoidance-plan.pdf"
    if hashlib.sha256(pdf.read_bytes()).hexdigest() != SOURCE_SHA256:
        raise ValueError("original plan PDF checksum mismatch")
    state = json.loads((ROOT / ".omp/roadmap/roadmap.json").read_text(encoding="utf-8"))
    check_roadmap(state)
    documents = [ROOT / "README.md", ROOT / ".omp/AGENTS.md", *sorted((ROOT / "docs").glob("*.md"))]
    scenario_text = (ROOT / "docs/SCENARIOS.md").read_text(encoding="utf-8")
    ids = re.findall(r"^\| ([A-F]\d{2}) \|", scenario_text, re.M)
    expected = {f"{letter}{n:02}" for letter, count in
                [("A", 10), ("B", 7), ("C", 8), ("D", 5), ("E", 25), ("F", 10)]
                for n in range(1, count+1)}
    if len(ids) != len(expected) or set(ids) != expected:
        raise ValueError("scenario table has missing/duplicate IDs")
    for document in documents:
        text = document.read_text(encoding="utf-8")
        for reference in re.findall(r"\b[A-F]\d{2}\b", text):
            if reference not in expected:
                raise ValueError(f"undefined scenario {reference} in {document.name}")
        for target in re.findall(r"\[[^\]]*\]\(([^)]+)\)", text):
            if re.match(r"https?://|mailto:|#", target):
                continue
            local = (document.parent / unquote(target.split("#")[0])).resolve()
            if not local.is_relative_to(ROOT) or not local.exists():
                raise ValueError(f"invalid local link in {document.name}: {target}")
    for task in state["tasks"]:
        for reference in re.findall(r"\b[A-F]\d{2}\b", " ".join(task["acceptance"])):
            if reference not in expected:
                raise ValueError(f"undefined scenario {reference} in {task['id']}")
    evidence_count = check_evidence_root(ROOT / "docs/replay")
    summary = f"Integrity OK: PDF checksum, {len(state['tasks'])} acyclic tasks, 65 scenario IDs, local links and {evidence_count} evidence hashes"
    return state, summary


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--export-roadmap", action="store_true",
                        help="Regenerate docs/ROADMAP.md from canonical native state")
    args = parser.parse_args()
    try:
        state, summary = check()
        portable = ROOT / "docs/ROADMAP.md"
        labels = json.loads((ROOT / "docs/roadmap.en.json").read_text(encoding="utf-8"))
        content = portable_roadmap(state, labels)
        if args.export_roadmap:
            portable.write_text(content, encoding="utf-8")
        elif not portable.is_file() or portable.read_text(encoding="utf-8") != content:
            raise ValueError("portable roadmap stale; run python scripts/check_project.py --export-roadmap")
    except (OSError, ValueError, KeyError, TypeError, tarfile.TarError) as error:
        parser.exit(1, f"Integrity check failed: {error}\n")
    print(summary)


if __name__ == "__main__":
    main()
